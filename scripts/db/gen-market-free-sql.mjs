// Generates sql/004_features_market_free_v2{,_PROOF}.sql from the ONE denylist in src/engine/leakage.js
// (MARKET_KEY_PATTERN) and the shared parity table test/fixtures/leakage-keys.json, so the DB CHECK
// pred_features_market_free can never drift from the code guard. test/leakage-db-parity.test.js fails if the
// committed SQL differs from this output. Regenerate: node scripts/db/gen-market-free-sql.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { MARKET_KEY_PATTERN } from '../../src/engine/leakage.js';

const repo = new URL('../../', import.meta.url);
export const MIGRATION_PATH = 'sql/004_features_market_free_v2.sql';
export const PROOF_PATH = 'sql/004_features_market_free_v2_PROOF.sql';

export function keyTable() {
  return JSON.parse(readFileSync(new URL('test/fixtures/leakage-keys.json', repo), 'utf8'));
}

// JS regex source -> Postgres ARE literal. Both engines treat this pattern identically: it uses only
// alternation, literals, '?', (?:...) groups and ^/$ anchors on a single-line key, matched case-insensitively
// (JS flag 'i' <-> Postgres ~*). Anything outside that subset is refused so a future JS-only construct
// (lookbehind, \b, named groups, etc.) cannot silently change meaning in SQL.
export function sqlPattern(re = MARKET_KEY_PATTERN) {
  if (re.flags !== 'i') throw new Error(`MARKET_KEY_PATTERN flags must be exactly 'i' (got '${re.flags}')`);
  const src = re.source;
  if (!/^[A-Za-z0-9_|?:^$()]+$/.test(src)) throw new Error(`MARKET_KEY_PATTERN uses constructs outside the JS/Postgres-common subset: ${src}`);
  if (/\(\?[^:]/.test(src)) throw new Error('only (?:...) groups are allowed');
  return src;
}

const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;
const arr = (keys) => `array[${keys.map(lit).join(', ')}]::text[]`;

export function migrationBody(pattern = sqlPattern()) {
  return `-- Leakage guard v2 (DB parity with src/engine/leakage.js MARKET_KEY_PATTERN, commit c3decef).
-- Denies every venue-derived key at any depth (object keys inside arrays included), case-insensitive.
-- Re-adding the CHECK (not NOT VALID) re-validates every existing row inside this transaction: if any stored
-- feature vector failed the stricter rule the whole migration aborts and nothing changes.
alter table pred_feature_snapshots drop constraint if exists pred_feature_snapshots_market_free;

create or replace function pred_features_market_free(doc jsonb)
returns boolean
language sql
immutable
as $$
  select not exists (
    select 1
    from jsonb_path_query(coalesce(doc, '{}'::jsonb), 'strict $.**') as node(v)
    cross join lateral jsonb_object_keys(case when jsonb_typeof(node.v) = 'object' then node.v else '{}'::jsonb end) as k(key)
    where k.key ~* ${lit(pattern)}
  )
$$;

comment on function pred_features_market_free(jsonb) is
  'v2 GENERATED by scripts/db/gen-market-free-sql.mjs from src/engine/leakage.js MARKET_KEY_PATTERN; do not hand-edit';

alter table pred_feature_snapshots
  add constraint pred_feature_snapshots_market_free check (pred_features_market_free(features));
`;
}

export function renderMigration() {
  return `-- GENERATED FILE: node scripts/db/gen-market-free-sql.mjs (source: src/engine/leakage.js). Do not hand-edit.
-- 004_features_market_free_v2: replace the sql/002 CHECK pred_feature_snapshots_market_free with the code guard's
-- denylist (Polymarket / prediction-market / CLOB / Gamma / consensus / bid / ask / midpoint / venue spread /
-- order book / depth / last trade / outcomePrices / token + condition ids). Bare 'spread' / 'mid' inside a name
-- stay allowed (live features nbm_max_temp_spread_f, cmt6m_minus_target_mid).
-- Rollback: sql/004_features_market_free_v2_ROLLBACK.sql. Proof (always rolls back): sql/004_features_market_free_v2_PROOF.sql.

begin;

${migrationBody()}
commit;
`;
}

// Runs the migration and every assertion inside one transaction, then RAISEs with the result object, so the
// proof can never leave anything behind (also safe to run on production).
export function renderProof() {
  const { blocked, allowed } = keyTable();
  return `-- GENERATED FILE: node scripts/db/gen-market-free-sql.mjs. Do not hand-edit.
-- PROOF for 004_features_market_free_v2. Applies the migration, checks it, then raises PROOF_RESULT {...} which
-- aborts the transaction: nothing persists. Expected: existing_failing=0, blocked_mismatch=[], allowed_mismatch=[],
-- nested/array blocked, insert of a blocked key rejected by the CHECK, insert of live feature names accepted.

begin;

${migrationBody()}
do $proof$
declare
  r jsonb;
  ev text;
  ins_blocked text := 'not_run';
  ins_clean text := 'not_run';
begin
  select event_id into ev from pred_events order by event_id limit 1;
  if ev is not null then
    begin
      insert into pred_feature_snapshots (snapshot_id, event_id, model_id, cutoff_at, created_at, features)
        values ('proof-004-blocked', ev, 'proof', now(), now(), '{"pop_union":0.4,"detail":[{"polymarket_midpoint":0.41}]}');
      ins_blocked := 'ACCEPTED';
    exception when check_violation then ins_blocked := 'rejected';
    end;
    begin
      insert into pred_feature_snapshots (snapshot_id, event_id, model_id, cutoff_at, created_at, features)
        values ('proof-004-clean', ev, 'proof', now(), now(),
          '{"nbm_max_temp_spread_f":2.1,"cmt6m_minus_target_mid":-0.12,"guidance_error_table":{"end":1,"pop":[{"p06":10}]}}');
      ins_clean := 'accepted';
    exception when check_violation then ins_clean := 'REJECTED';
    end;
  end if;

  select jsonb_build_object(
    'constraint', (select pg_get_constraintdef(oid) from pg_constraint where conname = 'pred_feature_snapshots_market_free'),
    'existing_rows', (select count(*) from pred_feature_snapshots where snapshot_id not like 'proof-004-%'),
    'existing_failing', (select count(*) from pred_feature_snapshots where not pred_features_market_free(features)),
    'blocked_total', cardinality(${arr(blocked)}),
    'blocked_mismatch', (select coalesce(jsonb_agg(k), '[]') from unnest(${arr(blocked)}) k
      where pred_features_market_free(jsonb_build_object(k, 1))
         or pred_features_market_free(jsonb_build_object('a', jsonb_build_object('b', jsonb_build_array(1, jsonb_build_object(k, 1)))))),
    'allowed_total', cardinality(${arr(allowed)}),
    'allowed_mismatch', (select coalesce(jsonb_agg(k), '[]') from unnest(${arr(allowed)}) k
      where not pred_features_market_free(jsonb_build_object(k, 1))
         or not pred_features_market_free(jsonb_build_object('a', jsonb_build_array(jsonb_build_object(k, 1))))),
    'insert_blocked', ins_blocked,
    'insert_clean', ins_clean
  ) into r;
  raise exception 'PROOF_RESULT %', r;
end
$proof$;

rollback;
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(new URL(MIGRATION_PATH, repo), renderMigration());
  writeFileSync(new URL(PROOF_PATH, repo), renderProof());
  console.log(`wrote ${MIGRATION_PATH} ${PROOF_PATH}`);
}
