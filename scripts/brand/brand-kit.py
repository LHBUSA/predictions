# Mark: a probability distribution in a navy tile; the bright line is the PBE model, the hollow tick is the market —
# the space between them is the divergence the product measures. Wordmarks are outlined (Inter, SIL OFL 1.1).
import io, math, os
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

NAVY_TOP, NAVY_BOT = '#0d2a52', '#050f1f'
BLUE, BLUE_HI, MKT = '#3f8cff', '#8cc2ff', '#9db3cc'

def curve(x0, x1, base, mu, sd, h, n=48):
    pts = []
    for i in range(n + 1):
        x = x0 + (x1 - x0) * i / n
        pts.append((x, base - h * math.exp(-0.5 * ((x - mu) / sd) ** 2)))
    return pts

def path(pts):
    return 'M' + ' L'.join(f'{x:.2f},{y:.2f}' for x, y in pts)

def y_at(pts, x):
    return min(pts, key=lambda p: abs(p[0] - x))[1]

def mark(size=64, small=False, rounded=True, pad=0.0, uid='m'):
    # pad (fraction) shrinks the artwork inside a full-bleed tile (maskable / apple-touch safe zones)
    s = 64
    k = 1 - 2 * pad
    g = f'translate({s*pad:.2f},{s*pad:.2f}) scale({k:.4f})'
    pts = curve(7, 57, 48, 29, 8.2 if not small else 9.5, 30 if not small else 31)
    area = path(pts) + ' L57,48 L7,48 Z'
    mx, kx = 41, 21   # model line, market tick
    my = y_at(pts, mx)
    rx = 15 if rounded else 0
    body = f'''<defs>
<linearGradient id="{uid}bg" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="{NAVY_TOP}"/><stop offset="1" stop-color="{NAVY_BOT}"/></linearGradient>
<linearGradient id="{uid}fill" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="{BLUE}" stop-opacity=".95"/><stop offset="1" stop-color="{BLUE}" stop-opacity=".18"/></linearGradient>
</defs>
<rect width="64" height="64" rx="{rx}" fill="url(#{uid}bg)"/>
<g transform="{g}">'''
    if small:
        body += f'''<path d="{area}" fill="url(#{uid}fill)"/><path d="{path(pts)}" fill="none" stroke="{BLUE_HI}" stroke-width="3.2" stroke-linejoin="round"/>
<line x1="{mx}" y1="49" x2="{mx}" y2="{my-7:.2f}" stroke="#fff" stroke-width="5" stroke-linecap="round"/>'''
    else:
        body += f'''<line x1="7" y1="48.6" x2="57" y2="48.6" stroke="{MKT}" stroke-opacity=".45" stroke-width="1.4"/>
<path d="{area}" fill="url(#{uid}fill)"/><path d="{path(pts)}" fill="none" stroke="{BLUE_HI}" stroke-width="2.4" stroke-linejoin="round"/>
<line x1="{kx}" y1="48.6" x2="{kx}" y2="13" stroke="{MKT}" stroke-width="2" stroke-dasharray="2.6 2.4" stroke-linecap="round"/>
<circle cx="{kx}" cy="11" r="3" fill="{NAVY_BOT}" stroke="{MKT}" stroke-width="2"/>
<line x1="{mx}" y1="48.6" x2="{mx}" y2="14" stroke="#fff" stroke-width="3" stroke-linecap="round"/>
<circle cx="{mx}" cy="11" r="7.5" fill="{BLUE}" fill-opacity=".30"/><circle cx="{mx}" cy="11" r="4" fill="#fff"/>'''
    body += '</g>'
    return f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 64 64">{body}</svg>\n', body

def outline(text, font, px, x, y, tracking=0.0):
    f = TTFont(font); gs = f.getGlyphSet(); cmap = f.getBestCmap(); upm = f['head'].unitsPerEm
    sc = px / upm; out = []; cx = x
    for ch in text:
        gname = cmap.get(ord(ch))
        if gname is None: continue
        pen = SVGPathPen(gs)
        gs[gname].draw(TransformPen(pen, (sc, 0, 0, -sc, cx, y)))
        d = pen.getCommands()
        if d: out.append(d)
        cx += gs[gname].width * sc + tracking
    return ' '.join(out), cx - tracking

def wordmark(dark):
    ink = '#ffffff' if dark else '#0f2033'
    sub = '#79b4ff' if dark else '#1f63b5'
    _, mk = mark(uid='w')
    d1, w1 = outline('PropBetEdge', 'brand/fonts/inter-800.ttf', 30, 78, 36, tracking=-0.6)
    d2, w2 = outline('PREDICTIONS', 'brand/fonts/inter-700.ttf', 12.5, 79, 57, tracking=3.1)
    W = math.ceil(max(w1, w2) + 6)
    return f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="64" viewBox="0 0 {W} 64" role="img" aria-label="PropBetEdge Predictions"><title>PropBetEdge Predictions</title><g>{mk}</g><path d="{d1}" fill="{ink}"/><path d="{d2}" fill="{sub}"/></svg>\n'

os.makedirs('brand', exist_ok=True)
w = lambda p, s: io.open(p, 'w', encoding='utf-8', newline='\n').write(s)
w('brand/predictions-mark.svg', mark()[0])
w('brand/predictions-mark-small.svg', mark(small=True)[0])
w('brand/predictions-mark-maskable.svg', mark(rounded=False, pad=0.12, uid='k')[0])
w('brand/predictions-mark-touch.svg', mark(rounded=False, pad=0.06, uid='t')[0])
w('brand/predictions-wordmark.svg', wordmark(False))
w('brand/predictions-wordmark-dark.svg', wordmark(True))
w('favicon.svg', mark()[0])
print('brand vectors written')

