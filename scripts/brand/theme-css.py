# Generates the Dark theme block appended to site.css between /* theme:dark */ markers (run from the repo root).
# Light is the default; Dark applies for [data-theme=dark], and for [data-theme=system] when the OS prefers dark.
# Research-terminal palette: deep navy/charcoal, restrained accents, no neon. One source -> both selectors.
import re, pathlib

TOKENS = {
    '--bg': '#0b1522', '--panel': '#111d2c', '--panel-2': '#0e1928', '--ink': '#e4ebf3', '--ink-2': '#c0cddb',
    '--muted': '#93a5b8', '--faint': '#8a9db1', '--line': '#223449', '--line-2': '#1a2a3c',
    '--navy': '#24476f', '--blue': '#7fb0f5', '--blue-2': '#9cc3f1', '--blue-bg': '#132842', '--mkt': '#8293a6', '--mkt-bg': '#16243a',
    '--pos': '#52c39a', '--pos-bg': '#0f2a22', '--neg': '#ee957a', '--neg-bg': '#2e1a14', '--amber': '#e2b65a', '--amber-bg': '#2a2312',
    '--violet': '#b9a6ef', '--violet-bg': '#221b39',
    '--shadow': '0 1px 2px rgba(0,0,0,.35),0 8px 26px rgba(0,0,0,.28)',
}
# Literal light-only values in site.css that need a dark equivalent (everything else already uses tokens or is
# white-on-dark art that stays as is).
OVERRIDES = """
.topbar{background:rgba(11,21,34,.94)}
.subnav{background:rgba(11,21,34,.96)}
.controls{background:linear-gradient(var(--bg) 85%,rgba(11,21,34,0))}
.skel{background:linear-gradient(90deg,var(--line-2),#1d2e42,var(--line-2));background-size:200% 100%}
.row:hover{border-color:#355074}
.mem-chip[data-state=all_access],.mem-chip[data-state=owner]{background:#2a2312;color:#e9c46a;border-color:#8a6a10}
.prem{background:linear-gradient(180deg,#1a1a12,var(--panel));border-color:#6b5520}
.ix-dbar{background:#18273a}
.ix-update{background:#0f2a22;border-color:#24604a}
.ix-ring{background:var(--panel)!important}
.chart svg line[stroke="#e9eff6"],.chart svg line[stroke="#dde6f0"]{stroke:#22344a}
.chart svg text{fill:#8a9db1}
.div-heat.heat-1.pos{background:rgba(82,195,154,.12)}.div-heat.heat-1.neg{background:rgba(238,149,122,.12)}
.div-heat.heat-2.pos{background:rgba(82,195,154,.2)}.div-heat.heat-2.neg{background:rgba(238,149,122,.2)}
.div-heat.heat-3.pos{background:rgba(82,195,154,.3)}.div-heat.heat-3.neg{background:rgba(238,149,122,.3)}
.nav a:hover,.nav a[aria-current=page],.subnav a[aria-current=page]{color:var(--ink)}
.cat{color:var(--blue-2)}
"""

def scoped(sel_prefix):
    out = []
    for line in [l for l in OVERRIDES.strip().splitlines() if l.strip()]:
        for rule in re.findall(r'([^{}]+)\{([^{}]*)\}', line):
            sels = ','.join(f'{sel_prefix} {s.strip()}' for s in rule[0].split(','))
            out.append(f'{sels}{{{rule[1]}}}')
    return '\n'.join(out)

tok = ';'.join(f'{k}:{v}' for k, v in TOKENS.items())
dark = ':root[data-theme="dark"]'
system = ':root[data-theme="system"]'
block = f"""/* theme:dark — GENERATED by scripts/brand/theme-css.py; do not hand-edit */
:root{{color-scheme:light}}
{dark}{{color-scheme:dark;{tok}}}
{scoped(dark)}
@media (prefers-color-scheme:dark){{
{system}{{color-scheme:dark;{tok}}}
{scoped(system)}
}}
/* theme toggle (header) */
.theme-btn{{display:inline-flex;align-items:center;gap:6px;height:32px;padding:0 10px;border:1px solid var(--line);border-radius:999px;background:var(--panel);color:var(--ink-2);font:650 12.5px var(--font);cursor:pointer}}
.theme-btn:hover{{border-color:var(--muted)}}
.theme-btn svg{{width:16px;height:16px;fill:none;stroke:currentColor;stroke-width:1.8;stroke-linecap:round;stroke-linejoin:round}}
.theme-btn[data-theme-toggle] svg path[d^="M20 14.6"]{{fill:currentColor;stroke:none}}
.theme-btn{{width:32px;padding:0;justify-content:center}}.theme-btn .theme-label{{position:absolute;width:1px;height:1px;overflow:hidden;clip:rect(0 0 0 0);white-space:nowrap}}
/* /theme:dark */"""

p = pathlib.Path('site.css')
s = p.read_text(encoding='utf-8')
s = re.sub(r'\n?/\* theme:dark — GENERATED.*?/\* /theme:dark \*/\n?', '\n', s, flags=re.S)
p.write_text(s.rstrip('\n') + '\n' + block + '\n', encoding='utf-8')
print('theme block written', len(block))
