// Deterministic vendoring of the Members live-score adapters into Compare.
//   source  test/fixtures/members-59de9d2/live.js.txt  (byte copy of LHBUSA/members api/live.js @ 59de9d2)
//   output  api/_lib/scores/adapters.js
// Run: node compare/scripts/vendor-members-live.mjs [--check]
// The drift test (test/scores.test.js) re-runs transform() and requires a byte-identical output, so the vendored
// adapters can only change by re-pinning the fixture + re-running this script.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

export const MEMBERS_COMMIT = '59de9d2';
export const MEMBERS_LIVE_SHA256 = '9307be0b2efa0b05de9d6cc00c96e27ad14e26d6576c580fb0e35ccac83da292';
const FIXTURE = new URL('../test/fixtures/members-59de9d2/live.js.txt', import.meta.url);
const OUTPUT = new URL('../api/_lib/scores/adapters.js', import.meta.url);

function replaceOnce(s, from, to, label) {
  const n = s.split(from).length - 1;
  if (n !== 1) throw new Error(`vendor patch "${label}": expected 1 match, found ${n}`);
  return s.replace(from, to);
}

export function transform(src) {
  const sha = createHash('sha256').update(src).digest('hex');
  if (sha !== MEMBERS_LIVE_SHA256) throw new Error(`pinned Members live.js changed: ${sha}`);
  let s = src;
  // PATCH 1: Compare makes its own (single) entitlement decision; the Members gate is not imported.
  s = replaceOnce(s, "import { memberAccess } from './_member-auth.js';\n",
    `// GENERATED by compare/scripts/vendor-members-live.mjs from LHBUSA/members api/live.js @ ${MEMBERS_COMMIT}\n` +
    `// (sha256 ${MEMBERS_LIVE_SHA256}). Do not edit by hand. Patches: (1) no Members auth import,\n` +
    '// (2) getJson accepts headers, (3) NHL gateway Origin, (4) tennis player media in live rows, (5) HTTP handler -> exported loadBoard(),\n' +
    '// (6) Compare source timeout is 6.5 s so a transient sport API read does not disappear at 4.2 s,\n' +
    '// (7) WNBA sides use the schedule\'s team_id/abbr + the WNBA product\'s verified team mark (Members wnbaSide rule),\n' +
    '// (8) golf keeps edition id/slug, ordered leaders + top leaderboard rows and the edition UUID as market_id.\n', 'auth import');
  // PATCH 2: getJson accepts extra request headers.
  // PATCH 6: Compare is a fan-in product; give each direct score source a little more room than Members.
  s = replaceOnce(s, 'const SOURCE_TIMEOUT_MS = 4200;', 'const SOURCE_TIMEOUT_MS = 6500;', 'Compare score source timeout');
  s = replaceOnce(s, 'async function getJson(url) {', 'async function getJson(url, extraHeaders = {}) {', 'getJson signature');
  s = replaceOnce(s, "headers: { accept: 'application/json', 'user-agent': 'PropBetEdge-Members/1.0' },",
    "headers: { accept: 'application/json', 'user-agent': 'PropBetEdge-Compare/1.0', ...extraHeaders },", 'getJson headers');
  // PATCH 3: nhl-api answers 403 without the NHL product Origin (verified 2026-10-05). Server-side caller only.
  // FOLLOW-UP (compare/README.md): replace Origin-as-server-auth with an internal caller contract.
  s = replaceOnce(s, 'const body = await getJson(`https://nhl-api.propbetedge.ai/nhl/board?date=${date}`);',
    "const body = await getJson(`https://nhl-api.propbetedge.ai/nhl/board?date=${date}`, { origin: 'https://nhl.propbetedge.ai' });", 'nhl origin');
  // PATCH 4: preserve tennis player ids/photos from the already-fetched live payload so Compare can render
  // first-class live score cards without a second tennis API request.
  s = replaceOnce(s,
    "        summary:{ label:'SETS', value:\`${setsA || '—'}  ·  ${setsB || '—'}\`, secondary:m?.tournament?.name || m?.edition?.name || null },",
    "        summary:{ label:'SETS', value:\`${setsA || '—'}  ·  ${setsB || '—'}\`, secondary:m?.tournament?.name || m?.edition?.name || null },\n        meta:{ sides:m?.sides || null },",
    'tennis player media');

  // PATCH 7 (2026-10-07): the WNBA schedule names a side by team_id (not id) and carries its own abbr, so the 59de9d2
  // teamSide() left id '' and logo null (score-only WNBA cards had no marks). Same rule current Members ships
  // (LHBUSA/members api/live.js wnbaSide): the verified WNBA product team mark for an approved team id, else none.
  s = replaceOnce(s, 'async function wnba() {',
    "// WNBA team marks: served by the WNBA product for the approved team ids only (never guessed from a name).\n" +
    "const WNBA_TEAM_IDS = new Set(['3','5','6','8','9','11','14','16','17','18','19','20','129689','131935','132052']);\n" +
    "const wnbaLogo = (id) => WNBA_TEAM_IDS.has(String(id ?? '')) ? `https://wnba.propbetedge.ai/media/teams/${String(id)}/128.webp` : null;\n" +
    "function wnbaSide(t) {\n" +
    "  const side = teamSide(t);\n" +
    "  if (t?.abbr) side.abbr = String(t.abbr);\n" +
    "  if (!side.id) side.id = String(t?.team_id || '');\n" +
    "  if (!side.logo) side.logo = wnbaLogo(t?.team_id ?? side.id);\n" +
    "  return side;\n" +
    "}\n\n" +
    'async function wnba() {', 'wnba side helper');
  s = replaceOnce(s, "      const away = teamSide(g?.away), home = teamSide(g?.home);\n      return makeEvent({\n        id:g.game_id || g.id, sport:'wnba',",
    "      const away = wnbaSide(g?.away), home = wnbaSide(g?.home);\n      return makeEvent({\n        id:g.game_id || g.id, sport:'wnba',", 'wnba sides');
  // PATCH 8 (2026-10-07): golf. The golf live payload Compare already reads carries edition.id (the UUID the market
  // desk keys the outright field by), edition.slug (golf routes) and Golf's own ordered leaders / leaderboard. Keep
  // them: market_id = edition.id is the deterministic market join (the Members _market-strip rule slug -> edition
  // UUID, here without a second read); meta.golf is a compact live board for the rail. Positions, scores and thru
  // are Golf's own values, never re-ranked or derived here.
  s = replaceOnce(s, "        updatedAt:ev?.updated_at || body?.generated_at || null\n      });\n    })\n  };\n}",
    "        updatedAt:ev?.updated_at || body?.generated_at || null,\n" +
    "        meta:{ golf:golfBoard(ev) }\n" +
    "      });\n" +
    "      return { ...item, market_id: ev?.edition?.id ? String(ev.edition.id) : null };\n" +
    "    })\n  };\n}\n\n" +
    "const GOLF_BOARD_ROWS = 5;\n" +
    "function golfRow(r) {\n" +
    "  return { slug:r?.slug || null, name:r?.name || r?.player?.name || null, position:r?.position ?? null, tied:r?.tied ?? null, status:r?.status ?? null,\n" +
    "    total_to_par:r?.total_to_par ?? null, today_to_par:r?.today_to_par ?? null, thru:r?.thru ?? null, tee_time:r?.tee_time ?? null };\n" +
    "}\n" +
    "function golfBoard(ev) {\n" +
    "  const board = arr(ev?.leaderboard);\n" +
    "  return {\n" +
    "    edition_id:ev?.edition?.id || null, edition_slug:ev?.edition?.slug || null, round:ev?.round ?? null,\n" +
    "    course:ev?.course?.name || null, tour:ev?.tour || null, field_size:board.length || ev?.players || null,\n" +
    "    leaders:arr(ev?.leaders).map(golfRow),\n" +
    "    leaderboard:board.slice(0, GOLF_BOARD_ROWS).map(golfRow)\n" +
    "  };\n" +
    "}", 'golf board');
  s = replaceOnce(s, "      return makeEvent({\n        id:slug || ev?.edition?.id, sport:'golf',", "      const item = makeEvent({\n        id:slug || ev?.edition?.id, sport:'golf',", 'golf item');

  // PATCH 5: the HTTP handler (and its Members membership gate) becomes a pure loader.
  const cut = s.indexOf('export default async function handler(req,res) {');
  if (cut < 0) throw new Error('vendor patch "handler": not found');
  const tail = s.slice(cut);
  const start = tail.indexOf("  const wanted = String(req.query?.sports || '').trim().toLowerCase();");
  const end = tail.indexOf('  return res.status(200).json({');
  if (start < 0 || end < 0) throw new Error('vendor patch "handler body": anchors not found');
  const body = tail.slice(start, end).replace("  const wanted = String(req.query?.sports || '').trim().toLowerCase();", "  const wanted = String(sports || '').trim().toLowerCase();");
  s = s.slice(0, cut) +
    'export { SPORTS, LOADERS };\n\n' +
    '// members-live/1 board for the requested sports (comma list; empty = all). Never throws: a failing source\n' +
    '// is reported as state "unavailable" with its error, exactly like the Members route.\n' +
    'export async function loadBoard(sports = \'\') {\n' + body +
    '  return {\n' +
    "    contract:'members-live/1',\n" +
    '    generated_at:NOW(),\n' +
    '    duration_ms:Date.now()-started,\n' +
    "    live_count:items.filter((x) => x.status === 'live').length,\n" +
    '    total:items.length,\n' +
    '    items,\n' +
    '    sources:settled.map(({key,state,ms,fetched_at,items,error}) => ({key,state,ms,fetched_at,count:items.length,...(error?{error}:{} )}))\n' +
    '  };\n}\n';
  return s;
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].replace(/\\/g, '/').split('/').pop())) {
  const out = transform(readFileSync(FIXTURE, 'utf8'));
  if (process.argv.includes('--check')) {
    const cur = readFileSync(OUTPUT, 'utf8');
    if (cur !== out) { console.error('api/_lib/scores/adapters.js is out of date: re-run vendor-members-live.mjs'); process.exit(1); }
    console.log('adapters.js matches the pinned transform');
  } else { writeFileSync(OUTPUT, out); console.log(`wrote api/_lib/scores/adapters.js from Members ${MEMBERS_COMMIT}`); }
}
