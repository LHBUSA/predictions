// Editorial image resolver for Insights stories (owner 2026-10-04: no more one-image-per-vertical).
//   1. bespoke flagship art (story.image)                       -> type 'art'
//   2. REAL PHOTO of the story's verified subject (+ evidence SVG overlay in the hero, render.js) -> type 'photo'
//      photo-registry.json: explicit Wikidata entity verified by label + coordinates, Commons license metadata
//      (built offline by scripts/brand/photo-registry.mjs, derivatives by photo-derivatives.py; nothing fetched at
//      request time, so publication never waits on an external image lookup)
//   3. STORY-SPECIFIC SVG generated from the story's own evidence (seeded by the story id) -> type 'svg'
//   4. category art — emergency fallback only (a story with no id and no subject)       -> type 'art', fallback
// Derivatives keep the fixed sizes/ratios of the editorial art (zero CLS). Numbers/headlines are never baked in.
import { SITE } from '../pages.js';
import REGISTRY from './photo-registry.json' with { type: 'json' };

// Bump ART_REV when derivatives change without a new image_version (busts edge and social caches).
export const ART_REV = '3';
export const IMAGE_CREDIT = 'Original illustration © PropBetEdge Predictions (code-generated editorial art)';
export const SVG_CREDIT = 'Data illustration generated by PropBetEdge Predictions from this story’s evidence';

const CATEGORY_ART = {
  weather: { key: 'category-weather', focal: '68% 42%', alt: 'Abstract isobar contours over a dark navy field — PropBetEdge Predictions weather analysis.' },
  rates: { key: 'category-rates', focal: '55% 45%', alt: 'A glowing yield curve across a dark financial grid — PropBetEdge Predictions rates analysis.' },
  economics: { key: 'category-economics', focal: '60% 60%', alt: 'A series of data bars on a dark grid with one period highlighted — PropBetEdge Predictions economics analysis.' },
  science: { key: 'category-science', focal: '60% 55%', alt: 'Structured blocks on a dark navy field — PropBetEdge Predictions science analysis.' },
  space: { key: 'category-space', focal: '50% 55%', alt: 'Orbital paths around a planet limb against a star field — PropBetEdge Predictions space analysis.' },
  'public-health': { key: 'category-public-health', focal: '55% 50%', alt: 'A network of connected nodes on a dark field — PropBetEdge Predictions public-health analysis.' },
  energy: { key: 'category-energy', focal: '50% 50%', alt: 'Layered power waveforms across a dark field — PropBetEdge Predictions energy analysis.' },
  business: { key: 'category-business', focal: '50% 60%', alt: 'Stacked structural blocks on a dark navy field — PropBetEdge Predictions business analysis.' },
};

const PHOTO_BY_STATION = new Map();
for (const s of Object.values(REGISTRY.subjects)) for (const cli of s.stations) PHOTO_BY_STATION.set(cli, s);
export const photoForStation = (cli) => (cli ? PHOTO_BY_STATION.get(cli) || null : null);

const rasterSet = (base) => [[`${base}/hero-1600.jpg`, 1600, 900], [`${base}/card-1200.jpg`, 1200, 900], [`${base}/square-1080.jpg`, 1080, 1080]];

// Resolve a story's image record (hero_image, hero_alt, hero_focal_point, og_image, image_credit, image_version, ...).
export function storyImage(story) {
  if (story.image) return rasterRecord(story, { ...story.image, type: 'art' }, IMAGE_CREDIT);
  const photo = photoForStation(story.subject?.station);
  if (photo) {
    const c = photo.credit;
    return { ...rasterRecord(story, { key: photo.key, version: photo.version, focal: photo.focal, alt: `${photo.alt.split(' — ')[0]} — photograph (${c.attribution})`, type: 'photo' }, c.attribution),
      credit: c, match: photo.match, overlay: true };
  }
  if (story.story_id || story.subject) {
    const key = `svg-${story.story_id || story.slug}`;
    return { type: 'svg', key, base: null, fallback: false, seed: story.story_id || story.slug, hero_image: null, hero_alt: svgAlt(story), hero_focal_point: '50% 50%',
      og_image: `${SITE}/og/insights/${story.slug}.png?v=svg1.${ART_REV}`, og_background: null, image_credit: SVG_CREDIT, image_version: 'svg1', schema: [], overlay: true };
  }
  return rasterRecord(story, { ...(CATEGORY_ART[story.vertical] || CATEGORY_ART.weather), version: 'v1', fallback: true, type: 'art' }, IMAGE_CREDIT);
}

function rasterRecord(story, img, credit) {
  const base = `/images/insights/${img.key}/${img.version}`;
  return {
    type: img.type, key: img.key, base, fallback: Boolean(img.fallback),
    hero_image: `${base}/hero-1600.jpg`, hero_alt: img.alt, hero_focal_point: img.focal,
    og_image: `${SITE}/og/insights/${story.slug}.png?v=${img.version}.${ART_REV}.${img.key}`,
    og_background: `${SITE}${base}/og-bg.jpg?r=${ART_REV}`,
    image_credit: credit, image_version: img.version, schema: rasterSet(base), overlay: false,
  };
}

function svgAlt(story) {
  const o = story.overlay;
  if (o?.kind === 'mover') return `Data illustration: the PBE forecast path for “${o.label}” ${o.to > o.from ? 'rising' : 'falling'} between two published snapshots.`;
  if (o?.kind === 'resolution') return 'Data illustration: the final PBE outcome distribution for this resolved event.';
  return 'Data illustration generated from this story’s evidence.';
}

