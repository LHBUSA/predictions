// Evidence geometry (no text, no numbers baked in). Overlay = drawn over the photo; full = the Tier 3 artwork.
const rng = (seed) => { let h = 2166136261; for (const ch of String(seed)) h = Math.imul(h ^ ch.charCodeAt(0), 16777619); return () => { h += 0x6d2b79f5; let t = h; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }; };

function evidencePaths(o, { x0, x1, y0, y1 }) {
  const y = (p) => y1 - (p / 100) * (y1 - y0);
  if (o?.kind === 'mover') {
    const a = [x0, y(o.from)], b = [x1, y(o.to)];
    const c1 = [x0 + (x1 - x0) * 0.45, a[1]], c2 = [x0 + (x1 - x0) * 0.55, b[1]];
    const grid = [25, 50, 75].map((p) => `<line x1="${x0}" x2="${x1}" y1="${y(p).toFixed(1)}" y2="${y(p).toFixed(1)}" class="ev-grid"/>`).join('');
    return `${grid}<line x1="${x0}" x2="${x0}" y1="${y0}" y2="${y1}" class="ev-axis"/><line x1="${x1}" x2="${x1}" y1="${y0}" y2="${y1}" class="ev-axis"/>`
      + `<path d="M${a[0]},${a[1].toFixed(1)} C${c1[0]},${c1[1].toFixed(1)} ${c2[0]},${c2[1].toFixed(1)} ${b[0]},${b[1].toFixed(1)}" class="ev-path"/>`
      + `<circle cx="${a[0]}" cy="${a[1].toFixed(1)}" r="7" class="ev-from"/><circle cx="${b[0]}" cy="${b[1].toFixed(1)}" r="10" class="ev-to"/>`;
  }
  if (o?.kind === 'resolution' && o.values?.length) {
    const n = o.values.length; const w = (x1 - x0) / n;
    return o.values.map((v, i) => { const hh = (Math.max(1, v) / 100) * (y1 - y0); return `<rect x="${(x0 + i * w + w * 0.18).toFixed(1)}" y="${(y1 - hh).toFixed(1)}" width="${(w * 0.64).toFixed(1)}" height="${hh.toFixed(1)}" rx="3" class="${i === o.winner ? 'ev-win' : 'ev-bar'}"/>`; }).join('');
  }
  return '';
}

// Tier 2: evidence overlay drawn into the right side of the photo hero (under the shade and the copy).
export function heroOverlaySvg(story) {
  const g = evidencePaths(story.overlay, { x0: 1060, x1: 1460, y0: 170, y1: 730 });
  return g ? `<svg class="ix-hero-overlay" viewBox="0 0 1600 900" preserveAspectRatio="xMidYMid slice" aria-hidden="true">${g}</svg>` : '';
}

// Tier 3: the full story-specific artwork (seeded field lines + the story's evidence geometry).
export function storySvg(story, { w = 1600, h = 900 } = {}) {
  const r = rng(story.story_id || story.slug);
  const hue = 205 + Math.round(r() * 30);
  const lines = Array.from({ length: 9 }, (_, i) => {
    const base = h * (0.18 + i * 0.085) + (r() - 0.5) * 30; const amp = 18 + r() * 46; const ph = r() * Math.PI * 2; const fq = 1.2 + r() * 1.6;
    let d = ''; for (let x = 0; x <= w; x += 40) d += `${x ? 'L' : 'M'}${x},${(base + Math.sin(ph + (x / w) * Math.PI * fq) * amp).toFixed(1)} `;
    return `<path d="${d}" fill="none" stroke="hsl(${hue} 70% ${55 + i * 3}%)" stroke-opacity="${(0.08 + r() * 0.12).toFixed(2)}" stroke-width="${(1 + r() * 1.6).toFixed(1)}"/>`;
  }).join('');
  const g = evidencePaths(story.overlay, { x0: w * 0.62, x1: w * 0.92, y0: h * 0.18, y1: h * 0.82 });
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" preserveAspectRatio="xMidYMid slice" aria-hidden="true"><defs><radialGradient id="g" cx="72%" cy="40%" r="75%"><stop offset="0" stop-color="hsl(${hue} 60% 16%)"/><stop offset="1" stop-color="#020a16"/></radialGradient></defs><rect width="${w}" height="${h}" fill="url(#g)"/>${lines}<g class="ev">${g}</g></svg>`;
}
